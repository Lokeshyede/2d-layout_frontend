export type WallPositionAnchor = 'start' | 'center' | 'end';

export interface WallPlacementData {
  wallId: string;
  anchor: WallPositionAnchor;
  offsetInches: number; // Distance in inches from chosen anchor point
  widthInches: number; // Measured along the wall
  heightInches?: number;
  depthInches?: number;
  rotation?: number;
}

export interface BaseCADEntity {
  id: string;
  type: EntityType;
  layer?: string;
  zIndex?: number;
  selected?: boolean;
}

export interface WallEntity extends BaseCADEntity {
  type: 'wall';
  geometry: {
    x1: number;
    y1: number;
    x2: number;
    y2: number;
  };
  properties: {
    thickness: number; // inches, e.g. 9 or 6
    color?: string;
    isExterior?: boolean;
  };
}

export interface ColumnEntity extends BaseCADEntity {
  type: 'column';
  geometry: {
    x: number; // center x
    y: number; // center y
    width: number; // inches, e.g. 24 (2'-0")
    height: number; // inches, e.g. 24 (2'-0")
    rotation?: number;
  };
  properties: {
    columnType: 'wall' | 'free'; // Wall Column or Free Column
    inwardProjection?: number; // inches, e.g. 24 (2'-0")
    attachedWallId?: string;
    wallOffset?: number;
    wallPlacement?: WallPlacementData;
  };
}

export interface DoorEntity extends BaseCADEntity {
  type: 'door';
  geometry: {
    x: number; // center or insertion point
    y: number;
    width: number; // inches, e.g. 36 (3'-0")
    height?: number; // thickness of wall or door height
    rotation: number; // degrees
  };
  properties: {
    doorType: 'single' | 'double';
    swing: 'inward' | 'outward';
    flipSide: 'left' | 'right';
    attachedWallId?: string;
    frameThickness?: number;
    wallPlacement?: WallPlacementData;
  };
}

