export interface RackEntity extends BaseCADEntity {
  type: 'rack';
  geometry: {
    x: number;
    y: number;
    width: number; // length along wall/aisle, e.g. 36, 48, 84, 96 inches
    depth: number; // e.g. 18, 24, 36 inches
    height?: number; // e.g. 84 inches (7'-0")
    rotation: number;
  };
  properties: {
    rackType: 'wall_rack_7x3' | 'wall_rack_7x4' | 'center_rack_5x3' | 'endcap_5x3' | 'corner_rack_2x2x2' | 'CUSTOM' | 'custom_rack' | 'Wall Rack' | 'Center Gondola' | 'Corner Rack' | 'End Cap' | string;
    productModelId?: string;
    productName?: string;
    sku?: string;
    baseWidth?: number;
    baseDepth?: number;
    baseHeight?: number;
    scalingMode?: 'stretch' | 'fit' | string;
    label?: string;
    /** Explicit canonical dimensions (numeric inches) */
    canonicalWidth?: number;
    canonicalDepth?: number;
    canonicalHeight?: number;
    width?: number;
    depth?: number;
    height?: number;
    isCustom?: boolean;
    shelves?: number; // legacy
    shelfCount?: number;
    shelfSpacing?: number | 'auto';
    shelfThickness?: number;
    color?: string;
    category?: string;
    attachedWallId?: string;
    wallOffset?: number;
    wallPlacement?: WallPlacementData;
    /** For wall racks: which room wall this rack is anchored to */
    wallSide?: 'top' | 'bottom' | 'left' | 'right';
    /** For corner racks: which room corner this rack occupies */
    cornerPosition?: 'top-left' | 'top-right' | 'bottom-left' | 'bottom-right';
    /** For wall racks: distance along wall from wall start point (inches) */
    positionAlongWall?: number;
    /** Inward normal vector pointing into room polygon */
    inwardNormal?: Point2D;
    /** Host wall thickness (inches) */
    wallThickness?: number;
    /** Whether this rack was generated by the AI planner */
    isAIGenerated?: boolean;
  };
  rackType?: string;
  width?: number;
  depth?: number;
  height?: number;
  label?: string;
}

